/* ==========================================================
   GONGBANS — catalogue / filter / search (boards.html)
   Vanilla JS, no framework. Loads data/catalog.json (slim grid
   data generated by build_catalog.py), renders cards in pages of
   60 with "Show more" + auto-load on scroll, wires up filter chips
   and instant search. Filters are mirrored into the URL hash so a
   view can be linked (#cat=IoT&q=zigbee).
   ========================================================== */

(async function () {
  const grid = document.getElementById('gongban-grid');
  const searchInput = document.getElementById('search-input');
  const entryCount = document.getElementById('entry-count');
  const showMoreBtn = document.getElementById('show-more');
  const sentinel = document.getElementById('grid-sentinel');
  const chips = document.querySelectorAll('.filter-chip');

  const PAGE = 60;
  let data = null;
  let filtered = [];
  let shown = 0;

  const state = {
    category: 'all',
    files: null,        // null | 'full-pack' | 'source-files' | 'metadata-only'
    query: ''
  };

  // --- restore state from URL hash (#cat=IoT&status=full-pack&q=esp32) ---
  (function readHash() {
    const h = new URLSearchParams(location.hash.replace(/^#/, ''));
    if (h.get('cat')) state.category = h.get('cat');
    if (h.get('status')) state.files = h.get('status');
    if (h.get('q')) state.query = h.get('q');
  })();

  function writeHash() {
    const h = new URLSearchParams();
    if (state.category !== 'all') h.set('cat', state.category);
    if (state.files) h.set('status', state.files);
    if (state.query) h.set('q', state.query);
    const s = h.toString();
    history.replaceState(null, '', s ? '#' + s : location.pathname);
  }

  // --- load ---
  try {
    const res = await fetch('data/catalog.json');
    data = await res.json();
  } catch (e) {
    grid.innerHTML = `<div class="empty-state">⚠ Couldn't load the catalogue. If running locally, serve via <code>python3 -m http.server</code>.</div>`;
    console.error(e);
    return;
  }

  // Pre-compute one lowercase haystack per entry so search stays instant.
  data.gongbans.forEach(g => {
    g._hay = [
      g.name, g.chip, g.chip_brand, g.issuer, g.application, g.category,
      g.project_no, g.hint, (g.tags || []).join(' ')
    ].filter(Boolean).join(' ').toLowerCase();
  });

  const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const fmt = n => n.toLocaleString('en-US');

  // --- filter ---
  function filter(gongbans) {
    const q = state.query.toLowerCase();
    return gongbans.filter(g => {
      if (state.category !== 'all' && g.category !== state.category) return false;
      if (state.files && g.status !== state.files) return false;
      if (q && !g._hay.includes(q)) return false;
      return true;
    });
  }

  // --- card ---
  const STATUS_LABEL = {
    'full-pack': 'Full Design Pack',
    'source-files': 'Design files at source',
    'metadata-only': 'Catalog entry'
  };

  function renderCard(g) {
    const id = g.project_no || g.issuer || '';
    const tag = [g.category, g.chip || g.hint].filter(Boolean).join(' · ');
    const desc = g.application || (g.chip ? `${esc(g.chip_brand)} ${esc(g.chip)}`.trim() : '');
    const right = g.price
      ? `CHIP <strong>$${g.price.toFixed(2)}</strong> / 5k`
      : [g.openness_label, g.year].filter(Boolean).join(' · ');

    return `
      <a class="board" href="db/${esc(g.slug)}.html">
        <div class="board-id">${esc(id)}</div>
        <h3 class="board-name">${esc(g.name)}</h3>
        <div class="board-tag">${esc(tag)}</div>
        <p class="board-desc clamp">${esc(desc)}</p>
        <div class="board-foot">
          <span class="status ${esc(g.status)}">${STATUS_LABEL[g.status] || ''}</span>
          <span class="meta">${right}</span>
        </div>
      </a>`;
  }

  // --- incremental render ---
  function appendPage() {
    const slice = filtered.slice(shown, shown + PAGE);
    grid.insertAdjacentHTML('beforeend', slice.map(renderCard).join(''));
    shown += slice.length;
    updateCount();
  }

  function updateCount() {
    const total = data.gongbans.length;
    if (filtered.length === total) {
      entryCount.textContent = `${fmt(Math.min(shown, total))} OF ${fmt(total)} ENTRIES`;
    } else {
      entryCount.textContent = `${fmt(Math.min(shown, filtered.length))} OF ${fmt(filtered.length)} MATCHES · ${fmt(total)} ENTRIES`;
    }
    const more = filtered.length - shown;
    showMoreBtn.hidden = more <= 0;
    showMoreBtn.textContent = more > 0 ? `Show ${fmt(Math.min(more, PAGE))} more · ${fmt(more)} left` : '';
  }

  function render() {
    filtered = filter(data.gongbans);
    shown = 0;
    grid.innerHTML = '';
    if (filtered.length === 0) {
      grid.innerHTML = `<div class="empty-state">No boards match these filters. Try clearing the search or category.</div>`;
      updateCount();
      return;
    }
    appendPage();
    writeHash();
  }

  showMoreBtn.addEventListener('click', appendPage);

  if ('IntersectionObserver' in window && sentinel) {
    new IntersectionObserver(entries => {
      if (entries.some(e => e.isIntersecting) && shown < filtered.length) appendPage();
    }, { rootMargin: '600px 0px' }).observe(sentinel);
  }

  // --- chips ---
  function syncChips() {
    chips.forEach(chip => {
      const t = chip.dataset.filter, v = chip.dataset.value;
      const on = t === 'category' ? state.category === v : state.files === v;
      chip.classList.toggle('active', on);
      chip.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
  }

  chips.forEach(chip => {
    chip.addEventListener('click', () => {
      const filterType = chip.dataset.filter;
      const value = chip.dataset.value;
      if (filterType === 'category') {
        state.category = value;
      } else if (filterType === 'files') {
        state.files = state.files === value ? null : value;   // toggle
      }
      syncChips();
      render();
    });
  });

  // --- search (debounced) ---
  let searchTimer = null;
  searchInput.addEventListener('input', e => {
    clearTimeout(searchTimer);
    searchTimer = setTimeout(() => {
      state.query = e.target.value.trim();
      render();
    }, 120);
  });
  document.addEventListener('keydown', e => {
    if (e.key === '/' && document.activeElement !== searchInput) { e.preventDefault(); searchInput.focus(); }
  });

  // --- initial ---
  searchInput.value = state.query;
  syncChips();
  render();
})();
