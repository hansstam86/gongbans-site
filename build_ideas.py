def board_item(b, boards):
    g = boards[b["board_slug"]]
    kinds = set((b.get("open_files") or "").split(",")) - {""}
    is_open = bool(kinds & OPEN_KINDS)
    icon = "OPEN" if is_open else "SPEC"
    files = ", ".join(sorted(kinds)) if kinds else "documentation only"
    sub = " · ".join(x for x in [b.get("issuer"), files] if x)
    return (f'<a class="file-link" href="/db/{e(g["slug"])}.html" title="{e(g["name"])}">'
            f'<span class="file-icon">{icon}</span><span class="file-name">{e(g["name"])}<small>{e(b["role"])}</small><small>{e(sub)}</small></span></a>')


def no_est(v):
    """Round-2 values already end in '(estimate)'; the table adds its own estimate label."""
    return re.sub(r"\s*\(estimate\)\s*$", "", v)


