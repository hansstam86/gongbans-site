ROOT = Path(__file__).parent
IDEAS_JSON = ROOT / "data" / "ideas.json"
MANIFEST = ROOT / "data" / "gongbans.json"
OUT_DIR = ROOT / "ideas"
OUT_DIR.mkdir(exist_ok=True)

DISCLAIMER = ("Concept generated by the GONGBANS inventor from the public catalogue. Not a product, not validated; "
              "estimates are rough; check each board's licence before commercial use.")
SCORE_KEYS = [("demand", "Demand", "How many European buyers want it"), ("buildability", "Buildability", "How far the catalogue boards carry you"),
              ("margin", "Margin", "Room between estimated BOM and price"), ("speed", "Speed", "How fast a small team ships V1")]
OPEN_KINDS = {"schematic", "pcb", "gerber"}
TAG_CHIPS = 14
PACKS = set()  # slugs that have a founder start pack (filled by main())
NEW_ROUND = 2  # ideas with this "round" get the "New" badge and the filter chip below
NEW_TAG = "new-r2"  # hidden filter tag (card data-tags only, never shown as a tag)
NEW_CHIP = "New · radar, Matter, LoRa"


def is_new(i):
    return i.get("round") == NEW_ROUND


def new_badge(i):
    return '<span class="new-badge" title="Added 17 Nov 2026 (round 2: radar, Matter, LoRa / sub-GHz)">New</span>' if is_new(i) else ""


def load():
    data = json.loads(IDEAS_JSON.read_text(encoding="utf-8"))
    ideas = sorted(data["ideas"], key=lambda i: (-i["score_total"], i["title"]))
    boards = {g["slug"]: g for g in json.loads(MANIFEST.read_text(encoding="utf-8"))["gongbans"]}
    missing = [b["board_slug"] for i in ideas for b in i["built_from"] if b["board_slug"] not in boards]
    if missing:
        raise SystemExit(f"ideas reference boards without a db page: {missing}")
    return data, ideas, boards


def score_pills(i, total_first=False):
    sc = i["scores"]
    pills = [f'<span class="score-pill" title="{e(lbl)}">{lbl[0]}<b>{sc[k]}</b></span>' for k, lbl, _ in SCORE_KEYS]
    total = f'<span class="score-pill total">Score<b>{i["score_total"]}</b>/20</span>'
    return f'<div class="score-row">{total if total_first else ""}{"".join(pills)}{"" if total_first else total}</div>'


def market_badge(i):
    mk = build_startpacks.MARKET.get(i["slug"])
    if not mk:
        return ""
    word = mk["verdict"].split()[0].lower()
    cls = word if word in ("likely", "weak", "uncertain") else "weak"
    return f'<span class="market-badge {cls}" title="External market check, November 2026: {e(mk["verdict"])}. Verify before relying on it.">Market: {e(word)}</span>'


def card(i, rank=None):
    tags = " ".join(sorted(i["tags"]) + ([NEW_TAG] if is_new(i) else []))
    hay = " ".join([i["title"], i["pitch"], i["audience"], i["category"], tags] + [b["board_name"] for b in i["built_from"]]).lower()
    sc = i["scores"]
    return f'''
    <a class="board idea{" has-pack" if i["slug"] in PACKS else ""}" href="/ideas/{e(i["slug"])}.html" data-pack="{int(i["slug"] in PACKS)}" data-cat="{e(i["category"])}" data-tags="{e(tags)}" data-score="{i["score_total"]}" data-d="{sc["demand"]}" data-b="{sc["buildability"]}" data-m="{sc["margin"]}" data-s="{sc["speed"]}" data-title="{e(i["title"].lower())}" data-hay="{e(hay)}">
      <div class="board-id">{f"#{rank} · " if rank else ""}{e(i["category"].upper())}</div>
      <h3 class="board-name">{e(i["title"])}{new_badge(i)}{'<span class="pack-badge" title="Founder start pack: business plan + start kit">Start pack</span>' if i["slug"] in PACKS else ""}{market_badge(i)}</h3>
      <div class="board-tag">{e(" · ".join(sorted(i["tags"])[:4]))}</div>
      <div class="board-desc clamp">{e(i["pitch"])}</div>
      {score_pills(i)}
      <div class="board-foot"><span class="status source-files">Built from {len(i["built_from"])} boards</span><span class="meta">{e(i["open_files_share"])}</span></div>
    </a>'''


