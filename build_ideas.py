def patch_index(ideas):
    """Idea count (<span data-stat="ideas">) on index.html and start.html; top-idea list on index.html."""
    top = "".join(f'<a href="/ideas/{e(i["slug"])}.html">{e(i["title"])}<small>{i["score_total"]}</small></a>' for i in ideas[:8])
    changed = False
    for name in ("index.html", "start.html"):
        path = ROOT / name
        if not path.exists():
            continue
        src = path.read_text(encoding="utf-8")
        out = re.sub(r'(<span data-stat="ideas"[^>]*>)[^<]*(</span>)', lambda m: f"{m.group(1)}{len(ideas)}{m.group(2)}", src)
        out = re.sub(r"(<!-- idea-top -->).*?(<!-- /idea-top -->)", lambda m: f"{m.group(1)}{top}{m.group(2)}", out, flags=re.S)
        if out != src:
            path.write_text(out, encoding="utf-8")
            changed = True
    return changed


def main():
    data, ideas, boards = load()
    build_contacts.patch_packs()
    build_validate.patch_packs()
    build_market.patch_packs()
    build_playbook.build()
    PACKS.update(build_startpacks.build(ideas))
    (ROOT / "ideas.html").write_text(render_index(data, ideas), encoding="utf-8")
    wanted = set()
    for i in ideas:
        p = OUT_DIR / f"{i['slug']}.html"
        wanted.add(p.name)
        p.write_text(render_idea(i, ideas, boards), encoding="utf-8")
    stale = [p for p in OUT_DIR.glob("*.html") if p.name not in wanted]
    for p in stale:
        p.unlink()
    print(f"ideas.html + ideas/: {len(wanted)} pages written, {len(stale)} stale removed")
    print(f"index.html: {'patched' if patch_index(ideas) else 'unchanged'}")


if __name__ == "__main__":
    main()
