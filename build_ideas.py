    n_new = sum(is_new(i) for i in ideas)
    tag_chips = (f'<button class="filter-chip" data-tag="{NEW_TAG}" type="button">{e(NEW_CHIP)}<small>{n_new}</small></button>' if n_new else "") + "".join(f'<button class="filter-chip" data-tag="{e(t)}" type="button">{e(t)}<small>{n}</small></button>'
                        for t, n in tags.most_common(TAG_CHIPS))
