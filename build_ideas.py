#!/usr/bin/env python3
"""
build_ideas.py — render the "Ideas" section of the site from data/ideas.json:

    ideas.html            grid of idea cards (static HTML; assets/ideas.js adds search, chips, sort)
    ideas/<slug>.html     one page per idea, boards linked to /db/<board_slug>.html
    index.html            the idea count in <span data-stat="ideas"> and the top-idea list
                          between <!-- idea-top --> markers

Run from the repo root (after build_detail_pages.py, which renders the
"Used in ideas" block on the board pages from the same JSON):
    python3 build_ideas.py

Shares head/nav/footer with build_detail_pages.py so the look stays identical.
Every number in the JSON is an estimate and is labelled as such.
"""

import json
import re
